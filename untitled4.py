import random

# Available choices
choices = ["rock", "paper", "scissors"]

# Score tracking
player_score = 0
computer_score = 0

# Store the player's previous moves
player_history = []

# Winning score
winning_score = 5


# Function to predict the player's next move
def predict_player_move():
    if len(player_history) == 0:
        return random.choice(choices)

    # Count the player's previous choices
    rock_count = player_history.count("rock")
    paper_count = player_history.count("paper")
    scissors_count = player_history.count("scissors")

    # Predict the most frequently used move
    counts = {
        "rock": rock_count,
        "paper": paper_count,
        "scissors": scissors_count
    }

    highest_count = max(counts.values())

    # If all moves are equally frequent, choose randomly
    most_common = [
        move for move, count in counts.items()
        if count == highest_count
    ]

    return random.choice(most_common)


# Function to choose the computer's move
def get_computer_move():
    predicted_move = predict_player_move()

    # Choose a move that beats the prediction
    winning_moves = {
        "rock": "paper",
        "paper": "scissors",
        "scissors": "rock"
    }

    computer_move = winning_moves[predicted_move]

    return computer_move


# Function to find the winner
def find_winner(player, computer):
    if player == computer:
        return "draw"

    if (
        (player == "rock" and computer == "scissors")
        or (player == "paper" and computer == "rock")
        or (player == "scissors" and computer == "paper")
    ):
        return "player"

    return "computer"


# Main game
print("=" * 40)
print(" AI-BASED ROCK-PAPER-SCISSORS GAME ")
print("=" * 40)

print("Rules:")
print("Rock beats Scissors")
print("Paper beats Rock")
print("Scissors beats Paper")
print("First to score", winning_score, "points wins!")
print()

while player_score < winning_score and computer_score < winning_score:

    # Get the player's choice
    player_move = input(
        "Choose rock, paper, or scissors: "
    ).lower().strip()

    if player_move not in choices:
        print("Invalid choice! Please try again.")
        continue

    # Computer predicts and selects a move
    computer_move = get_computer_move()

    print("Your choice:", player_move)
    print("Computer's choice:", computer_move)

    # Find the result
    result = find_winner(player_move, computer_move)

    if result == "draw":
        print("It's a draw!")

    elif result == "player":
        print("You win this round!")
        player_score += 1

    else:
        print("Computer wins this round!")
        computer_score += 1

    # Save the player's move for future predictions
    player_history.append(player_move)

    # Display scores
    print("\nCurrent Score:")
    print("Player:", player_score)
    print("Computer:", computer_score)
    print("-" * 40)


# Final result
print("\nGAME OVER!")

if player_score == winning_score:
    print("Congratulations! You won the game!")
else:
    print("The computer won the game!")

print("Final Score:")
print("Player:", player_score)
print("Computer:", computer_score)
print("Total rounds played:", len(player_history))